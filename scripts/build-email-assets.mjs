#!/usr/bin/env node
/**
 * Builds the two images every Sougouba email carries, from the web brand kit.
 *
 * An email cannot use the kit as it is: Gmail and Outlook draw no SVG, and a
 * remote image is blocked until the reader clicks "show images" — which, on a
 * sign-in code, is a logo-shaped hole in the one message that has to look like
 * it came from us. So the images are rasterised here and travel *inside* the
 * message as inline attachments (`cid:`), where every client shows them at once.
 *
 * Output: api/src/mail/brand-assets.generated.ts — the PNGs as base64, not as
 * files. The API is built by `nest build`, which compiles TypeScript and copies
 * nothing else; a PNG that failed to reach `dist/` would only be discovered
 * when the first email went out without its header.
 *
 *   lockup   the basket and the wordmark side by side, as in the site's header.
 *            `wordmark-dark.svg` — the variant drawn for the forest slab — so
 *            nothing here re-sets or recolours the wordmark.
 *   band     the woven band (`band-dark.svg`), three tiles wide, which is the
 *            exact width of the email.
 *
 * Both are transparent and sit on the slab colour set in `brand-email.ts`.
 * Rendered at 2x: an email is read on a phone more often than not.
 *
 * Run: node scripts/build-email-assets.mjs
 * Needs `npm install` in web/ — sharp comes from there.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const BRAND = join(ROOT, 'web/public/brand');
const OUT = join(ROOT, 'api/src/mail/brand-assets.generated.ts');

const sharp = createRequire(join(ROOT, 'web/package.json'))('sharp');

/** Device pixels per email pixel. */
const SCALE = 2;
const CLEAR = { r: 0, g: 0, b: 0, alpha: 0 };

/** An SVG drawn at exactly `height` device pixels, keeping its own proportions. */
async function raster(file, height) {
  // Rasterised large, then reduced: librsvg at its default 72 dpi would draw
  // the logo's 270 paths small and leave sharp to enlarge the result.
  const image = sharp(readFileSync(join(BRAND, file)), { density: 600 }).resize({ height, fit: 'inside' });
  const { data, info } = await image.png().toBuffer({ resolveWithObject: true });
  return { data, width: info.width, height: info.height };
}

/** A palette PNG — a flat-colour logo and a three-colour weave need no more. */
const quantise = (image, colours) =>
  image.png({ palette: true, colours, effort: 10, compressionLevel: 9 }).toBuffer();

// ── lockup: basket + wordmark ───────────────────────────────────────────────

const LOCKUP_H = 38; // email px
const WORDMARK_H = 34;
const GAP = 10;

const mark = await raster('mark.svg', LOCKUP_H * SCALE);
const wordmark = await raster('wordmark-dark.svg', WORDMARK_H * SCALE);
const lockupWidth = mark.width + GAP * SCALE + wordmark.width;
// An even width, so the email-px size is a whole number.
const lockupCanvas = lockupWidth + (lockupWidth % 2);

const lockup = await quantise(
  sharp({ create: { width: lockupCanvas, height: LOCKUP_H * SCALE, channels: 4, background: CLEAR } }).composite([
    { input: mark.data, left: 0, top: 0 },
    {
      input: wordmark.data,
      left: mark.width + GAP * SCALE,
      top: Math.round((LOCKUP_H * SCALE - wordmark.height) / 2),
    },
  ]),
  128
);

// ── band: three tiles ───────────────────────────────────────────────────────

const EMAIL_WIDTH = 600;
const TILES = 3;
const TILE_W = (EMAIL_WIDTH / TILES) * SCALE; // 400 device px
// The tile is 8:1 by construction (web/lib/band.ts), so the height follows.
const TILE_H = TILE_W / 8;

const tile = await sharp(readFileSync(join(BRAND, 'band-dark.svg')), { density: 600 })
  .resize({ width: TILE_W, height: TILE_H, fit: 'fill' })
  .png()
  .toBuffer();

const band = await quantise(
  sharp({ create: { width: TILE_W * TILES, height: TILE_H, channels: 4, background: CLEAR } }).composite(
    Array.from({ length: TILES }, (_, i) => ({ input: tile, left: i * TILE_W, top: 0 }))
  ),
  32
);

// ── write ───────────────────────────────────────────────────────────────────

/** Base64 in 100-character lines, so a regenerated image is a readable diff rather than one endless line. */
function chunks(buffer) {
  const base64 = buffer.toString('base64');
  const lines = base64.match(/.{1,100}/g) ?? [];
  return lines.map((line) => `    '${line}',`).join('\n');
}

const image = (name, { cid, filename, alt, width, height, buffer }) => `export const ${name}: BrandImage = {
  cid: '${cid}',
  filename: '${filename}',
  alt: '${alt}',
  width: ${width},
  height: ${height},
  content: png([
${chunks(buffer)}
  ]),
};
`;

const source = `/**
 * GENERATED by scripts/build-email-assets.mjs — do not edit by hand; re-run it.
 *
 * The images every Sougouba email carries, as base64. They are sent inside the
 * message as inline attachments and referenced as \`cid:\`, because an email
 * client draws no SVG and blocks a remote image until the reader allows it.
 * \`width\` and \`height\` are the size on screen; the pixels are ${SCALE}x that.
 */

export interface BrandImage {
  /** What the HTML references as \`cid:…\`. */
  cid: string;
  filename: string;
  /** Empty for an image that is decoration: a screen reader should skip it. */
  alt: string;
  width: number;
  height: number;
  content: Buffer;
}

const png = (lines: string[]): Buffer => Buffer.from(lines.join(''), 'base64');

/** The basket and the wordmark, for the forest slab. ${lockup.length} bytes. */
${image('BRAND_LOCKUP', {
  cid: 'lockup@sougouba',
  filename: 'sougouba.png',
  alt: 'Sougouba',
  width: lockupCanvas / SCALE,
  height: LOCKUP_H,
  buffer: lockup,
})}
/** The woven band, three tiles — the full width of an email. ${band.length} bytes. */
${image('BRAND_BAND', {
  cid: 'band@sougouba',
  filename: 'sougouba-band.png',
  alt: '',
  width: EMAIL_WIDTH,
  height: TILE_H / SCALE,
  buffer: band,
})}`;

writeFileSync(OUT, source);
console.log(`lockup  ${lockupCanvas}x${LOCKUP_H * SCALE}px  ${lockup.length} bytes`);
console.log(`band    ${TILE_W * TILES}x${TILE_H}px  ${band.length} bytes`);
console.log(`wrote   ${OUT.replace(`${ROOT}/`, '')}`);
